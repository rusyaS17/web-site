// ТЕСТ НӘТИЖЕЛЕРІН САҚТАУ
function saveTestResults(lectureId, score, correct, total, timeSpent) {
    try {
        const lecture = lectures.find(l => l.id === lectureId);
        if (!lecture) {
            console.error('Лекция табылмады:', lectureId);
            return;
        }
        
        const testResult = {
            lectureId: lectureId,
            lectureTitle: lecture.title,
            score: score,
            correct: correct,
            total: total,
            timeSpent: timeSpent,
            date: new Date().toISOString()
        };
        
        console.log('Сақталатын нәтиже:', testResult);
        
        // Барлық тест нәтижелерін алу
        let allResults = JSON.parse(localStorage.getItem('test_results')) || {};
        
        console.log('Бұрынғы нәтижелер:', allResults);
        
        // Осы лекцияның нәтижелерін сақтау
        if (!allResults[lectureId]) {
            allResults[lectureId] = [];
        }
        
        allResults[lectureId].push(testResult);
        
        // Соңғы 5 нәтижені ғана сақтау
        if (allResults[lectureId].length > 5) {
            allResults[lectureId] = allResults[lectureId].slice(-5);
        }
        
        localStorage.setItem('test_results', JSON.stringify(allResults));
        localStorage.setItem(`test_score_${lectureId}`, score);
        
        console.log('Сақталған нәтижелер:', allResults);
        console.log('Сақталған score:', score);
        
        return true;
    } catch (error) {
        console.error('Нәтижелерді сақтау қатесі:', error);
        return false;
    }
}

