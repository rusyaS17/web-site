// ПРОГРЕСТІ ЖАҢАРТУ
function updateProgress() {
    const lecturesCompleted = userProgress.lectures.filter(l => l).length;
    const labsCompleted = userProgress.labs.filter(l => l).length;
    const testsCompleted = userProgress.tests.filter(t => t).length;
    const tasksCompleted = userProgress.tasks.filter(t => t).length;
    
    // Ең көп мүмкін балл: 15 (лекция) + 9 (зертхана) + 15 (тест) + 15 (тапсырма) = 54
    const totalProgress = Math.round((lecturesCompleted + labsCompleted + testsCompleted + tasksCompleted) / 54 * 100);
    
    document.getElementById('progress-value').textContent = `${totalProgress}%`;
    document.getElementById('lectures-completed').textContent = `${lecturesCompleted}/15`;
    document.getElementById('labs-completed').textContent = `${labsCompleted}/9`;  // 15-тен 9-ға өзгерттік
    document.getElementById('tests-completed').textContent = `${testsCompleted}/15`;
    document.getElementById('tasks-completed').textContent = `${tasksCompleted}/15`;
    
    // Прогресс шеңберін жаңарту
    const progressCircle = document.getElementById('progress-circle');
    progressCircle.style.background = `conic-gradient(var(--secondary-color) ${totalProgress}%, var(--border-color) 0)`;
}

