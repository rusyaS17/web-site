// ТЕСТТІ БАСТАУ
window.startTest = function(lectureId) {
    currentTest = lectureId;
    testState = {
        currentQuestion: 0,
        answers: [],
        startTime: Date.now(),
        timer: null
    };
    
    const questions = testQuestions[lectureId] || generateTestQuestions(lectureId);
    if (!questions || questions.length === 0) {
        alert('Бұл лекция үшін тест әзірленбеген.');
        return;
    }
    
    showTestModal(questions);
};

// ТЕСТ МОДАЛЫН КӨРСЕТУ
function showTestModal(questions) {
    document.getElementById('test-title').textContent = `Тест: Лекция ${currentTest}`;
    renderTestQuestion(questions[0], 0, questions.length);
    showModal('test-modal');
    
    // Таймерді бастау
    startTestTimer();
    
    // Батырмаларды байлау
    document.getElementById('prev-question-btn').onclick = () => {
        if (testState.currentQuestion > 0) {
            testState.currentQuestion--;
            renderTestQuestion(questions[testState.currentQuestion], testState.currentQuestion, questions.length);
        }
    };
    
    document.getElementById('next-question-btn').onclick = () => {
        saveCurrentAnswer();
        
        if (testState.currentQuestion < questions.length - 1) {
            testState.currentQuestion++;
            renderTestQuestion(questions[testState.currentQuestion], testState.currentQuestion, questions.length);
        } else {
            document.getElementById('submit-test-btn').style.display = 'block';
        }
    };
    
    document.getElementById('submit-test-btn').onclick = () => {
        finishTest(questions);
    };
}

// ТЕСТ СҰРАҒЫН РЕНДЕРЛЕУ
function renderTestQuestion(question, index, total) {
    const optionsHtml = question.options.map((option, optIndex) => `
        <div class="test-option" onclick="selectOption(this, ${optIndex})">
            <input type="radio" name="test-answer" id="opt${optIndex}" value="${optIndex}" 
                   ${testState.answers[index] === optIndex ? 'checked' : ''}>
            <label for="opt${optIndex}">${option}</label>
        </div>
    `).join('');
    
    document.getElementById('test-content').innerHTML = `
        <div class="test-question">
            <h4>${index + 1}. ${question.question}</h4>
            <div class="test-options">
                ${optionsHtml}
            </div>
        </div>
    `;
    
    // Прогресс
    const progress = ((index + 1) / total) * 100;
    document.getElementById('test-progress-bar').style.width = `${progress}%`;
    document.getElementById('test-progress-text').textContent = `${index + 1}/${total} сұрақ`;
    
    // Батырмалар
    document.getElementById('prev-question-btn').disabled = index === 0;
    document.getElementById('next-question-btn').style.display = index < total - 1 ? 'block' : 'none';
    document.getElementById('submit-test-btn').style.display = index === total - 1 ? 'block' : 'none';
}

// ОПЦИЯНЫ ТАҢДАУ
window.selectOption = function(element, optionIndex) {
    const radio = element.querySelector('input[type="radio"]');
    radio.checked = true;
    testState.answers[testState.currentQuestion] = optionIndex;
};

// ЖАУАПТЫ САҚТАУ
function saveCurrentAnswer() {
    const selected = document.querySelector('input[name="test-answer"]:checked');
    if (selected) {
        testState.answers[testState.currentQuestion] = parseInt(selected.value);
    }
}

// ТЕСТ ТАЙМЕРІ
function startTestTimer() {
    const timerElement = document.getElementById('test-time');
    let timeLeft = 1800; // 30 минут
    
    testState.timer = setInterval(() => {
        timeLeft--;
        
        const minutes = Math.floor(timeLeft / 60);
        const seconds = timeLeft % 60;
        timerElement.textContent = `${minutes.toString().padStart(2, '0')}:${seconds.toString().padStart(2, '0')}`;
        
        if (timeLeft <= 0) {
            finishTest(testQuestions[currentTest] || []);
        }
    }, 1000);
}

// ТЕСТТІ АЯҚТАУ
function finishTest(questions) {
    try {
        console.log('Тест аяқталуда...');
        clearInterval(testState.timer);
        
        // Нәтижелерді есептеу
        let correct = 0;
        testState.answers.forEach((answer, index) => {
            if (answer === questions[index].correct) {
                correct++;
            }
        });
        
        const score = Math.round((correct / questions.length) * 100);
        const timeSpent = Math.floor((Date.now() - testState.startTime) / 1000);
        
        console.log('Есептелген нәтиже:', { score, correct, total: questions.length, timeSpent });
        
        // Нәтижелерді сақтау
        const saved = saveTestResults(currentTest, score, correct, questions.length, timeSpent);
        console.log('Нәтиже сақталды ма?', saved);
        
        // Нәтижені көрсету (сақталған немесе сақталмаған)
        showResults(score, correct, questions.length, timeSpent);
        
        // Прогреске сақтау
        if (score >= 70) {
            userProgress.tests[currentTest-1] = true;
            localStorage.setItem('tests_progress', JSON.stringify(userProgress.tests));
            updateProgress();
            console.log('Прогресс жаңартылды');
        }
        
        // Тест күйін тазалау
        testState = {
            currentQuestion: 0,
            answers: [],
            startTime: null,
            timer: null
        };
        
    } catch (error) {
        console.error('Тестті аяқтау қатесі:', error);
        alert('Тестті аяқтау кезінде қате орын алды. Қайта тапсырып көріңіз.');
    }
}

