function setupNavigation() {
    const navLinks = document.querySelectorAll('.main-nav a');
    navLinks.forEach(link => {
        link.addEventListener('click', function(e) {
            if (this.getAttribute('href').startsWith('#')) {
                e.preventDefault();
                const targetId = this.getAttribute('href').substring(1);
                const targetElement = document.getElementById(targetId);
                
                if (targetElement) {
                    // Белсенді түймені жаңарту
                    navLinks.forEach(l => l.classList.remove('active'));
                    this.classList.add('active');
                    
                    // Скроллдау
                    window.scrollTo({
                        top: targetElement.offsetTop - 80,
                        behavior: 'smooth'
                    });
                }
            }
        });
    });
}

// ОҚИҒА ТЫҢДАУШЫЛАРЫН ҚОСУ
function setupEventListeners() {
    // Модалды терезені жабу
    document.getElementById('close-pdf-btn').addEventListener('click', () => hideModal('pdf-modal'));
    document.getElementById('close-test-btn').addEventListener('click', () => {
        if (testState.timer) clearInterval(testState.timer);
        hideModal('test-modal');
    });
    document.getElementById('close-task-btn').addEventListener('click', () => hideModal('task-modal'));
    document.getElementById('close-results-btn').addEventListener('click', () => hideModal('results-modal'));
    
    // Модалды терезенің сыртын басқанда жабу
    document.querySelectorAll('.modal').forEach(modal => {
        modal.addEventListener('click', (e) => {
            if (e.target === modal) {
                hideModal(modal.id);
            }
        });
    });
    
    // ESC пернесімен жабу
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape') {
            hideModal('pdf-modal');
            hideModal('test-modal');
            hideModal('task-modal');
            hideModal('results-modal');
        }
    });
}

// ІЗДЕУДІ БАПТАУ
function setupSearch() {
    const searchInput = document.getElementById('lecture-search');
    if (searchInput) {
        searchInput.addEventListener('input', function(e) {
            const searchTerm = e.target.value.toLowerCase();
            const cards = document.querySelectorAll('#lectures-container .card');
            
            cards.forEach(card => {
                const title = card.querySelector('h3').textContent.toLowerCase();
                const description = card.querySelector('p').textContent.toLowerCase();
                
                if (title.includes(searchTerm) || description.includes(searchTerm)) {
                    card.style.display = 'block';
                } else {
                    card.style.display = 'none';
                }
            });
        });
    }
}

// ТЕСТ СҰРАҚТАРЫН ГЕНЕРАЦИЯЛАУ
function generateTestQuestions(lectureId) {
    // Егер лекция үшін алдын ала дайын сұрақтар бар болса, оларды қайтарамыз
    if (testQuestions[lectureId]) {
        return testQuestions[lectureId];
    }
    
    // Егер жоқ болса, қарапайым тест сұрақтарын генерациялау
    return Array(10).fill().map((_, i) => ({
        id: i + 1,
        question: `Лекция ${lectureId} сұрағы ${i + 1}`,
        options: ['1-нұсқа', '2-нұсқа', '3-нұсқа', '4-нұсқа'],
        correct: Math.floor(Math.random() * 4)
    }));
}

