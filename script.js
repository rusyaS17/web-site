// PDF ФАЙЛДЫ ЖАҢА ВКЛАДКАДА АШУ
function openPdfInNewTab(pdfPath, title) {
    // PDF файлдың бар екенін тексеру
    fetch(pdfPath, { method: 'HEAD' })
        .then(response => {
            if (response.ok) {
                // PDF файлды жаңа вкладкада ашу
                window.open(pdfPath, '_blank');
            } else {
                // Егер файл жоқ болса, қате хабарлау
                alert(`${title} PDF файлы табылмады.\nФайл мына жерде болуы керек: ${pdfPath}`);
                // Өрнектеу үшін мысал PDF жасау
                createSamplePdf(pdfPath, title);
            }
        })
        .catch(error => {
            console.error('PDF файлын тексеру кезінде қате:', error);
            alert(`${title} PDF файлын ашу мүмкін болмады.\nФайлдың бар екенін тексеріңіз: ${pdfPath}`);
        });
}

// МҮЛТІМ ПРИМЕР PDF ЖАСАУ
function createSamplePdf(pdfPath, title) {
    // Егер файл жоқ болса, мысал PDF жасау (тек демонстрация үшін)
    const sampleContent = `
        <html>
        <head>
            <title>${title}</title>
            <style>
                body { font-family: Arial; padding: 40px; }
                h1 { color: #1a237e; }
                .content { max-width: 800px; margin: 0 auto; }
                .note { background: #fff3cd; padding: 20px; border-radius: 5px; margin: 20px 0; }
            </style>
        </head>
        <body>
            <div class="content">
                <h1>${title}</h1>
                <div class="note">
                    <strong>ЕСКЕРТУ:</strong> Бұл мысал PDF файл. Нақты PDF файлды "${pdfPath}" қалпына келтіріңіз.
                </div>
                <p>Бұл PDF файл деректер базасы курсының материалдарын қамтиды.</p>
                <h2>Мазмұны</h2>
                <ul>
                    <li>Кіріспе</li>
                    <li>Негізгі ұғымдар</li>
                    <li>Мысалдар</li>
                    <li>Тапсырмалар</li>
                    <li>Қорытынды</li>
                </ul>
                <p>Нақты PDF файлды мына папкаға орналастырыңыз: ${pdfPath}</p>
            </div>
        </body>
        </html>
    `;
    
    // HTML мәтінін Blob түріне айналдыру
    const blob = new Blob([sampleContent], { type: 'text/html' });
    const url = URL.createObjectURL(blob);
    window.open(url, '_blank');
    
    // Біраз уақыттан кейін URL босату
    setTimeout(() => URL.revokeObjectURL(url), 10000);
}

