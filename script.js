// ТАПСЫРМАНЫ ЖІБЕРУ
window.submitTask = function(lectureId) {
    const taskText = document.getElementById('task-text').value;
    const taskFile = document.getElementById('task-file').files[0];
    
    if (!taskText.trim() && !taskFile) {
        alert('Тапсырманың жауабын енгізіңіз немесе файл жүктеңіз!');
        return;
    }
    
    // Тапсырма деректерін жасау
    const taskData = {
        lectureId: lectureId,
        title: lectures.find(l => l.id === lectureId).title,
        text: taskText,
        fileName: taskFile ? taskFile.name : null,
        fileSize: taskFile ? taskFile.size : 0,
        submittedAt: new Date().toISOString(),
        status: 'жарияланды'
    };
    
    // Тапсырмаларды сақтау
    let submittedTasks = JSON.parse(localStorage.getItem('submitted_tasks')) || [];
    submittedTasks.push(taskData);
    localStorage.setItem('submitted_tasks', JSON.stringify(submittedTasks));
    
    // Прогреске сақтау
    userProgress.tasks[lectureId-1] = true;
    localStorage.setItem('tasks_progress', JSON.stringify(userProgress.tasks));
    updateProgress();
    
    hideModal('task-modal');
    
    // Тапсырманы көрсету модалы
    showTaskSubmissionDetails(taskData);
    
    // Өрістерді тазалау
    document.getElementById('task-text').value = '';
    document.getElementById('task-file').value = '';
};

